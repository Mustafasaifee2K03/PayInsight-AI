def h_kpi(c: Ctx) -> None:
    p, m = c.plan, METRICS[c.plan.metric]
    row = c.run(compile_aggregate(p, dimensions=[], purpose=f"{m.label}, {_range_txt(p.time_range)}"))[0]
    c.kpis.append(_card(p.metric, row, primary=True))
    for other in ("transaction_count", "success_rate", "failed_transactions", "tpv"):
        if other != p.metric:
            c.kpis.append(_card(other, row))
            c.use_metric(other)
    if not row["attempts"]:
        c.summary = f"No transactions matched {_range_txt(p.time_range)}{_filters_txt(p)}."
        return
    val = m.compute(row)
    nd = f" ({num(row[m.numerator])} of {num(row[m.denominator])} eligible attempts)" if m.unit == "percent" else ""
    c.summary = f"{m.label} was {fmt_metric(val, m.unit)}{nd} for {_range_txt(p.time_range)}{_filters_txt(p)}."
    c.facts.append(c.summary)
    c.facts.append(f"Status split: {num(row['successful'])} SUCCESS, {num(row['failed'])} FAILED, {num(row['pending'])} PENDING out of {num(row['attempts'])} canonical attempts.")
    excluded = row["attempts"] - row["eligible"]
    if m.unit == "percent" and excluded:
        c.facts.append(f"{num(excluded)} non-terminal or invalid-status attempts are excluded from the rate denominator (eligibility rule).")
    if p.metric in ("tpv", "avg_transaction_value"):
        c.caveats.append("TPV includes only successful INR transactions with a positive amount; other currencies are excluded, not converted.")
    if p.time_range.days > 1:
        daily = c.run(compile_daily(p, p.time_range, purpose="Daily trend for context"))
        c.charts.append(_daily_chart(daily, p.metric, f"Daily {m.label.lower()}"))


def _daily_chart(daily: list[dict], metric: str, title: str) -> dict:
    m = METRICS[metric]
    data = [{"day": r["day"], "value": m.compute(r), "attempts": r["attempts"]} for r in daily if r["day"]]
    series = [{"key": "value", "label": m.label, "unit": m.unit, "type": "line", "axis": "left"}]
    if metric != "transaction_count":
        series.append({"key": "attempts", "label": "Attempts", "unit": "count", "type": "bar", "axis": "right"})
    return {"id": f"daily_{metric}", "title": title, "type": "composed", "x_key": "day", "series": series, "data": data, "unit": m.unit}


def h_breakdown(c: Ctx) -> None:
    p, m = c.plan, METRICS[c.plan.metric]
    dims = p.dimensions
    limit = p.limit if p.intent == "ranking" else min(max(p.limit, 50), 100)
    rows = c.run(compile_aggregate(p, limit=limit, purpose=f"{m.label} by {', '.join(DIMENSIONS[d].label.lower() for d in dims)}"))
    total = c.run(compile_aggregate(p, dimensions=[], purpose="Overall benchmark (same filters and window)"))[0]
    overall = m.compute(total)
    is_fc = "failure_code" in dims
    table_rows = []
    for r in rows:
        label = " · ".join(str(r[d]) for d in dims)
        val = m.compute(r)
        tr = {"segment": label, **{d: r[d] for d in dims}, "attempts": r["attempts"], "eligible": r["eligible"],
              "successful": r["successful"], "failed": r["failed"], "metric_value": val,
              "share_pct": (100 * r["failed"] / total["failed"] if total["failed"] else None) if is_fc else
                           (100 * r["attempts"] / total["attempts"] if total["attempts"] else None),
              "low_sample": m.unit == "percent" and (r["eligible"] or 0) < 30}
        if m.unit == "percent" and val is not None and overall is not None:
            tr["vs_overall_pp"] = val - overall
        table_rows.append(tr)
    cols = [{"key": d, "label": DIMENSIONS[d].label, "format": "text"} for d in dims]
    cols += [{"key": "attempts", "label": "Attempts", "format": "count"}]
    if m.unit == "percent":
        cols += [{"key": "eligible", "label": "Eligible", "format": "count"}, {"key": m.numerator, "label": m.numerator.title(), "format": "count"}]
    elif not is_fc:
        cols += [{"key": "failed", "label": "Failed", "format": "count"}]
    cols += [{"key": "metric_value", "label": m.label, "format": m.unit}]
    cols += [{"key": "share_pct", "label": "Share of failures" if is_fc else "Share of attempts", "format": "percent"}]
    if m.unit == "percent":
        cols += [{"key": "vs_overall_pp", "label": "vs overall", "format": "pp"}]
    c.tables.append({"id": "breakdown", "title": f"{m.label} by {' & '.join(DIMENSIONS[d].label.lower() for d in dims)}", "columns": cols, "rows": table_rows})
    c.charts.append({
        "id": "breakdown_chart", "title": f"{m.label} by {' & '.join(DIMENSIONS[d].label.lower() for d in dims)}", "type": "bar",
        "x_key": "segment", "series": [{"key": "metric_value", "label": m.label, "unit": m.unit, "type": "bar"}],
        "data": [{"segment": t["segment"], "metric_value": t["metric_value"], "attempts": t["attempts"]} for t in table_rows[:25]],
        "unit": m.unit, "reference_lines": ([{"y": overall, "label": f"Overall {fmt_metric(overall, m.unit)}"}] if m.unit == "percent" else []),
    })
    c.kpis.append(_card(p.metric, total, primary=True, label=f"Overall {m.label.lower()}"))
    c.kpis.append(_card("transaction_count", total)); c.use_metric("transaction_count")
    if not table_rows:
        c.summary = f"No transactions matched {_range_txt(p.time_range)}{_filters_txt(p)}."
        return
    valid = [t for t in table_rows if t["metric_value"] is not None and not t["low_sample"]] or table_rows
    top, bottom = valid[0], valid[-1]
    dim_l = DIMENSIONS[dims[0]].label.lower() if len(dims) == 1 else "segment"
    if is_fc:
        c.summary = (f"The leading failure code was {top['segment']} with {num(top['failed'])} failures "
                     f"({top['share_pct']:.1f}% of {num(total['failed'])} failed transactions) for {_range_txt(p.time_range)}{_filters_txt(p)}.")
        for t in table_rows[:3]:
            c.facts.append(f"{t['segment']}: {num(t['failed'])} failures ({t['share_pct']:.1f}% of failures).")
            if t["segment"] in recs_mod.FAILURE_CODE_HYPOTHESES:
                c.hypotheses.append(f"{t['segment']} failures may reflect {recs_mod.FAILURE_CODE_HYPOTHESES[t['segment']]}.")
        top_code = table_rows[0]["segment"]
        c.recommendations.append(recs_mod.rec(f"Prioritise {top_code} reduction", recs_mod.FAILURE_CODE_ACTIONS.get(top_code, "Review logs."), "high"))
        return
    order_word = "highest" if p.sort == "desc" else "lowest"
    if p.intent == "ranking":
        listed = "; ".join(f"{t['segment']} ({fmt_metric(t['metric_value'], m.unit)})" for t in table_rows[:3])
        c.summary = (f"{dim_l.capitalize()}s ranked by {order_word} {m.label.lower()} (top {len(table_rows)} shown): {listed}. "
                     f"Overall {fmt_metric(overall, m.unit)} for {_range_txt(p.time_range)}{_filters_txt(p)}.")
    else:
        c.summary = (f"Across {len(table_rows)} {dim_l} segment(s), {top['segment']} has the {order_word} {m.label.lower()} "
                     f"({fmt_metric(top['metric_value'], m.unit)}) and {bottom['segment']} the {'lowest' if p.sort == 'desc' else 'highest'} "
                     f"({fmt_metric(bottom['metric_value'], m.unit)}); overall {fmt_metric(overall, m.unit)} for {_range_txt(p.time_range)}{_filters_txt(p)}.")
    c.facts.append(c.summary)
    for t in table_rows[:5]:
        extra = f", {num(t['eligible'])} eligible attempts" if m.unit == "percent" else f", {num(t['attempts'])} attempts"
        c.facts.append(f"{t['segment']}: {fmt_metric(t['metric_value'], m.unit)}{extra} ({t['share_pct']:.1f}% of attempts).")
    lows = [t for t in table_rows if t.get("low_sample")]
    if lows:
        c.caveats.append(f"{len(lows)} segment(s) have fewer than 30 eligible attempts; their rates are statistically unreliable.")
    unknown = [t for t in table_rows if UNKNOWN in t["segment"]]
    if unknown:
        c.caveats.append(f"'{UNKNOWN}' groups {num(sum(t['attempts'] for t in unknown))} attempts with missing or orphan dimension keys (see data quality).")
    if m.unit == "percent" and len(dims) == 1 and dims[0] != "day":
        worse_key = (lambda t: t.get("vs_overall_pp", 0)) if not m.higher_is_better else (lambda t: -t.get("vs_overall_pp", 0))
        laggards = [t for t in valid if t.get("vs_overall_pp") is not None and worse_key(t) >= 2.0 and UNKNOWN not in t["segment"]]
        for t in sorted(laggards, key=worse_key, reverse=True)[:2]:
            c.hypotheses.append(
                f"{t['segment']} is {abs(t['vs_overall_pp']):.2f} pp {'below' if m.higher_is_better else 'above'} the overall {m.label.lower()}. "
                "Possible explanations include segment-specific technical issues, issuer policies or a different customer mix; its failure-code mix would help distinguish these."
            )
            c.recommendations.append(recs_mod.rec(f"Drill into failure codes for {t['segment']}",
                                                  f"Ask: 'What are the main failure codes for {t['segment']}?' and compare with peers.", "medium"))


def h_trend(c: Ctx) -> None:
    p, m = c.plan, METRICS[c.plan.metric]
    daily = c.run(compile_daily(p, p.time_range, purpose=f"Daily {m.label.lower()}"))
    daily = [r for r in daily if r["day"]]
    chart = _daily_chart(daily, p.metric, f"Daily {m.label.lower()}{_filters_txt(p)}")
    seg_dims = [d for d in p.dimensions if d not in ("day",)]
    if seg_dims:
        d = seg_dims[0]
        rows = c.run(compile_aggregate(p, dimensions=["day", d], purpose=f"Daily {m.label.lower()} by {DIMENSIONS[d].label.lower()}", limit=5000, order="day ASC"))
        vol: dict[str, int] = {}
        for r in rows:
            vol[r[d]] = vol.get(r[d], 0) + r["attempts"]
        top = [s for s, _ in sorted(vol.items(), key=lambda kv: -kv[1])[:8]]
        pivot: dict[str, dict] = {}
        for r in rows:
            if r[d] in top and r["day"]:
                pivot.setdefault(r["day"], {"day": r["day"]})[r[d]] = m.compute(r)
        c.charts.append({"id": "trend_by_segment", "title": f"Daily {m.label.lower()} by {DIMENSIONS[d].label.lower()}", "type": "line",
                         "x_key": "day", "series": [{"key": s, "label": s, "unit": m.unit, "type": "line"} for s in top],
                         "data": [pivot[k] for k in sorted(pivot)], "unit": m.unit})
    c.charts.insert(0, chart)
    c.tables.append({"id": "daily", "title": "Daily values", "columns": [
        {"key": "day", "label": "Day", "format": "text"}, {"key": "attempts", "label": "Attempts", "format": "count"},
        {"key": "successful", "label": "Successful", "format": "count"}, {"key": "failed", "label": "Failed", "format": "count"},
        {"key": "metric_value", "label": m.label, "format": m.unit}],
        "rows": [{"day": r["day"], "attempts": r["attempts"], "successful": r["successful"], "failed": r["failed"], "metric_value": m.compute(r)} for r in daily]})
    if not daily:
        c.summary = f"No transactions matched {_range_txt(p.time_range)}{_filters_txt(p)}."
        return
    vals = [(r["day"], m.compute(r)) for r in daily if m.compute(r) is not None]
    hi, lo = max(vals, key=lambda x: x[1]), min(vals, key=lambda x: x[1])
    agg = {k: sum(r[k] or 0 for r in daily) for k in ("attempts", "successful", "failed", "pending", "eligible", "tpv_minor", "tpv_txn_count")}
    c.kpis.append(_card(p.metric, agg, primary=True, label=f"{m.label} (whole period)"))
    c.kpis.append({"metric": "avg_daily_attempts", "label": "Average attempts / day", "unit": "count", "value": agg["attempts"] / len(daily),
                   "formatted": num(agg["attempts"] / len(daily)), "primary": False})
    c.summary = (f"Over {_range_txt(p.time_range)}{_filters_txt(p)}, daily {m.label.lower()} ranged from {fmt_metric(lo[1], m.unit)} ({lo[0]}) "
                 f"to {fmt_metric(hi[1], m.unit)} ({hi[0]}); whole-period value {fmt_metric(m.compute(agg), m.unit)}.")
    c.facts.append(c.summary)
    if len(daily) >= 14:
        last7, prev7 = daily[-7:], daily[-14:-7]
        a1 = {k: sum(r[k] or 0 for r in last7) for k in agg}
        a0 = {k: sum(r[k] or 0 for r in prev7) for k in agg}
        v1, v0 = m.compute(a1), m.compute(a0)
        ch = change(v1, v0, m.unit)
        c.facts.append(f"Last 7 days vs previous 7 days: {fmt_metric(v0, m.unit)} → {fmt_metric(v1, m.unit)} "
                       f"({pp(ch['absolute']) if m.unit == 'percent' else fmt_metric(ch['absolute'], m.unit)}, {rel(ch['relative_pct'])} relative).")
    if len(daily) >= 21:
        an = daily_anomalies([{"day": r["day"], "v": METRICS["success_rate"].compute(r), "attempts": r["attempts"]} for r in daily], "v", daily[14]["day"])
        flagged = [a for a in an if a["flagged"]]
        if flagged:
            c.facts.append("Heuristic anomaly rule (|z| ≥ 3 vs trailing 14-day baseline) flagged success rate on: "
                           + ", ".join(f"{a['day']} ({pct(a['value'])}, z={a['z']:.1f})" for a in flagged[:5]) + ".")
            c.recommendations.append(recs_mod.rec("Investigate flagged days", "Ask 'Why did payment success rate decline?' for the affected window.", "medium"))


def _seg_decomp(c: Ctx, dim: str, purpose: str | None = None, extra: list[Filter] | None = None) -> dict:
    rows = c.run(compile_period_segments(c.plan, dim, purpose=purpose or f"Success rate by {DIMENSIONS[dim].label.lower()}: current vs previous period", extra_filters=extra))
    segs = segments_from_period_rows(rows)
    d = decompose(segs)
    d["dimension"] = dim
    d["dimension_label"] = DIMENSIONS[dim].label
    fail = {(s["segment"]): (s["b_failed"], s["c_failed"]) for s in segs}
    for s in d.get("segments", []):
        s["baseline_failed"], s["current_failed"] = fail.get(s["segment"], (0, 0))
    return d


def _decomp_table(d: dict, title: str, tid: str = "decomposition") -> dict:
    return {"id": tid, "title": title, "columns": [
        {"key": "segment", "label": d["dimension_label"], "format": "text"},
        {"key": "baseline_attempts", "label": "Attempts (prev)", "format": "count"},
        {"key": "current_attempts", "label": "Attempts (curr)", "format": "count"},
        {"key": "baseline_share_pct", "label": "Share prev", "format": "percent"},
        {"key": "current_share_pct", "label": "Share curr", "format": "percent"},
        {"key": "baseline_rate_pct", "label": "SR prev", "format": "percent"},
        {"key": "current_rate_pct", "label": "SR curr", "format": "percent"},
        {"key": "rate_change_pp", "label": "SR change", "format": "pp"},
        {"key": "within_effect_pp", "label": "Within effect", "format": "pp"},
        {"key": "mix_effect_pp", "label": "Mix effect", "format": "pp"},
        {"key": "contribution_pp", "label": "Contribution", "format": "pp"},
        {"key": "share_of_change_pct", "label": "% of change", "format": "percent"}],
        "rows": d.get("segments", [])}


def _overall_period(c: Ctx) -> tuple[dict, dict, float | None]:
    p = c.plan
    rows = c.run(compile_period_segments(p, None, purpose=f"Overall KPIs: {_range_txt(p.time_range)} vs {_range_txt(p.comparison_range)}"))
    b, cur = _period_rows(rows)
    for mname in PERIOD_KPI_METRICS:
        c.kpis.append(_card(mname, cur, b, primary=(mname == p.metric)))
        c.use_metric(mname)
    return b, cur, _sr_significance(b, cur)


def _change_sentence(c: Ctx, b: dict, cur: dict, z: float | None) -> str:
    p = c.plan
    m = METRICS[p.metric]
    v0, v1 = m.compute(b), m.compute(cur)
    ch = change(v1, v0, m.unit)
    sig = ""
    if z is not None and m.name in ("success_rate", "failure_rate"):
        sig = (f" The change is statistically significant (two-proportion z = {z:.1f})." if abs(z) >= SIGNIFICANCE_Z
               else f" The change is within normal statistical noise (two-proportion z = {z:.1f}).")
    absolute = pp(ch["absolute"]) if m.unit == "percent" else fmt_metric(ch["absolute"], m.unit)
    return (f"{m.label} moved from {fmt_metric(v0, m.unit)} ({p.comparison_range.label}, {p.comparison_range.start} to {p.comparison_range.end}) "
            f"to {fmt_metric(v1, m.unit)} ({p.time_range.label}, {p.time_range.start} to {p.time_range.end}): {absolute} absolute, "
            f"{rel(ch['relative_pct'])} relative{_filters_txt(p)}.{sig}")


def h_period(c: Ctx) -> None:
    p, m = c.plan, METRICS[c.plan.metric]
    b, cur, z = _overall_period(c)
    c.summary = _change_sentence(c, b, cur, z)
    c.facts.append(c.summary)
    c.facts.append(f"Attempts: {num(b['attempts'])} → {num(cur['attempts'])}; failed: {num(b['failed'])} → {num(cur['failed'])}. Both periods are {p.time_range.days} days long.")
    if p.dimensions:
        dim = p.dimensions[0]
        rows = c.run(compile_period_segments(p, dim, purpose=f"{m.label} by {DIMENSIONS[dim].label.lower()}: current vs previous"))
        segs: dict[str, dict] = {}
        for r in rows:
            segs.setdefault(r["segment"], {"segment": r["segment"], "baseline": None, "current": None})[r["period"]] = r
        table = []
        for s in segs.values():
            v0 = m.compute(s["baseline"]) if s["baseline"] else None
            v1 = m.compute(s["current"]) if s["current"] else None
            ch = change(v1, v0, m.unit)
            table.append({"segment": s["segment"], "baseline_attempts": (s["baseline"] or {}).get("attempts", 0),
                          "current_attempts": (s["current"] or {}).get("attempts", 0), "baseline_value": v0, "current_value": v1,
                          "change_abs": ch["absolute"], "change_rel_pct": ch["relative_pct"]})
        if m.name in ("success_rate", "failure_rate"):
            d = decompose(segments_from_period_rows(rows))
            contrib = {s["segment"]: s for s in d.get("segments", [])}
            sign = 1 if m.name == "success_rate" else -1
            for t in table:
                s = contrib.get(t["segment"], {})
                t["contribution_pp"] = sign * s["contribution_pp"] if s else None
            c.decomposition = {k: v for k, v in d.items() if k != "segments"} | {"dimension": dim}
        worse_first = m.higher_is_better
        table.sort(key=lambda t: (t["change_abs"] if t["change_abs"] is not None else 0) * (1 if worse_first else -1))
        unit_fmt = "pp" if m.unit == "percent" else m.unit
        cols = [{"key": "segment", "label": DIMENSIONS[dim].label, "format": "text"},
                {"key": "baseline_attempts", "label": "Attempts (prev)", "format": "count"},
                {"key": "current_attempts", "label": "Attempts (curr)", "format": "count"},
                {"key": "baseline_value", "label": f"{m.label} (prev)", "format": m.unit},
                {"key": "current_value", "label": f"{m.label} (curr)", "format": m.unit},
                {"key": "change_abs", "label": "Change", "format": unit_fmt},
                {"key": "change_rel_pct", "label": "Relative change", "format": "pct_change"}]
        if any("contribution_pp" in t for t in table):
            cols.append({"key": "contribution_pp", "label": "Contribution to overall change", "format": "pp"})
        c.tables.append({"id": "period_segments", "title": f"{m.label} by {DIMENSIONS[dim].label.lower()} — previous vs current", "columns": cols, "rows": table})
        c.charts.append({"id": "period_segments_chart", "title": f"{m.label} by {DIMENSIONS[dim].label.lower()}: previous vs current", "type": "grouped_bar",
                         "x_key": "segment", "unit": m.unit,
                         "series": [{"key": "baseline_value", "label": f"Previous ({p.comparison_range.start:%d %b}–{p.comparison_range.end:%d %b})", "unit": m.unit, "type": "bar"},
                                    {"key": "current_value", "label": f"Current ({p.time_range.start:%d %b}–{p.time_range.end:%d %b})", "unit": m.unit, "type": "bar"}],
                         "data": table[:20]})
        moved = [t for t in table if t["change_abs"] is not None]
        if moved:
            w = moved[0]
            ch_txt = pp(w["change_abs"]) if m.unit == "percent" else fmt_metric(w["change_abs"], m.unit)
            c.facts.append(f"Largest {'deterioration' if (w['change_abs'] < 0) == m.higher_is_better else 'movement'}: {w['segment']} "
                           f"{fmt_metric(w['baseline_value'], m.unit)} → {fmt_metric(w['current_value'], m.unit)} ({ch_txt}).")
            if m.unit == "percent" and w.get("contribution_pp") is not None and abs(cur_delta := (m.compute(cur) or 0) - (m.compute(b) or 0)) >= MATERIAL_CHANGE_PP:
                share = 100 * w["contribution_pp"] / cur_delta if cur_delta else 0
                c.facts.append(f"{w['segment']} contributes {pp(w['contribution_pp'])} of the overall {pp(cur_delta)} change ({share:.0f}%).")
                c.recommendations.append(recs_mod.rec(f"Investigate {w['segment']}", f"Ask 'Why did payment success rate decline?' for a full root-cause breakdown.", "medium"))
    daily_range = TimeRange(start=p.comparison_range.start, end=p.time_range.end, label="comparison window")
    daily = c.run(compile_daily(p, daily_range, purpose="Daily series across both periods"))
    chart = _daily_chart([r for r in daily if r["day"]], p.metric, f"Daily {m.label.lower()} across both periods")
    chart["reference_areas"] = [{"x1": p.time_range.start.isoformat(), "x2": p.time_range.end.isoformat(), "label": "Current period"}]
    c.charts.append(chart)


def h_contribution(c: Ctx, *, mix_focus: bool = False) -> None:
    p = c.plan
    dim = p.dimensions[0]
    b, cur, z = _overall_period(c)
    d = _seg_decomp(c, dim)
    c.decomposition = d
    if not d["valid"]:
        c.summary = d["reason"]
        return
    delta = d["direct_change_pp"]
    c.facts.append(_change_sentence(c, b, cur, z))
    c.facts.append(f"Decomposition by {d['dimension_label'].lower()}: within-segment effect {pp(d['within_effect_pp'])} + mix effect {pp(d['mix_effect_pp'])} "
                   f"= {pp(d['within_effect_pp'] + d['mix_effect_pp'])}; direct aggregate change {pp(delta)} (residual {d['residual_pp']:.2e} pp — identity verified).")
    c.tables.append(_decomp_table(d, f"Contribution to success-rate change by {d['dimension_label'].lower()}"))
    c.charts.append({"id": "contribution_chart", "title": f"Contribution to success-rate change by {d['dimension_label'].lower()} (pp)", "type": "stacked_bar",
                     "x_key": "segment", "unit": "pp",
                     "series": [{"key": "within_effect_pp", "label": "Within-segment (performance)", "unit": "pp", "type": "bar"},
                                {"key": "mix_effect_pp", "label": "Mix (share shift)", "unit": "pp", "type": "bar"}],
                     "data": d["segments"][:15]})
    if mix_focus:
        c.charts.append({"id": "share_chart", "title": f"Share of eligible attempts by {d['dimension_label'].lower()}", "type": "grouped_bar", "x_key": "segment",
                         "unit": "percent", "series": [{"key": "baseline_share_pct", "label": "Previous share", "unit": "percent", "type": "bar"},
                                                       {"key": "current_share_pct", "label": "Current share", "unit": "percent", "type": "bar"}],
                         "data": d["segments"]})
        c.charts.append({"id": "rate_chart", "title": f"Success rate by {d['dimension_label'].lower()}", "type": "grouped_bar", "x_key": "segment",
                         "unit": "percent", "series": [{"key": "baseline_rate_pct", "label": "Previous SR", "unit": "percent", "type": "bar"},
                                                       {"key": "current_rate_pct", "label": "Current SR", "unit": "percent", "type": "bar"}],
                         "data": d["segments"]})
    material = abs(delta) >= MATERIAL_CHANGE_PP and (z is None or abs(z) >= SIGNIFICANCE_Z)
    direction = "declined" if delta < 0 else "increased"
    if not material:
        c.summary = (f"Success rate did not change materially ({pp(delta)}, z = {z:.1f}); segment contributions below are small and likely noise."
                     if z is not None else f"Success rate did not change materially ({pp(delta)}).")
        c.verdict = {"type": "no_material_change", "label": "No material change"}
        return
    mix_frac = d["mix_effect_pp"] / delta
    top = d["segments"][0]
    if mix_focus:
        if mix_frac >= 0.6:
            vt, vl = "mix_shift", "Transaction mix shift"
        elif mix_frac >= 0.3:
            vt, vl = "both", "Both mix shift and performance deterioration"
        else:
            vt, vl = "performance", "Within-segment performance change (not mix)"
        c.verdict = {"type": vt, "label": vl, "mix_share_pct": 100 * mix_frac}
        c.summary = (f"Success rate {direction} by {pp(delta)}. By {d['dimension_label'].lower()}, mix explains {pp(d['mix_effect_pp'])} "
                     f"({100 * mix_frac:.0f}%) and within-segment performance {pp(d['within_effect_pp'])} ({100 * (1 - mix_frac):.0f}%). Verdict: {vl}.")
        movers = sorted(d["segments"], key=lambda s: -abs(s["share_change_pp"]))
        if vt in ("mix_shift", "both"):
            h, r = recs_mod.for_mix(d["dimension_label"], movers, d["mix_effect_pp"], d["within_effect_pp"])
            c.hypotheses += h; c.recommendations += r
        for s in movers[:3]:
            c.facts.append(f"{s['segment']}: share {pct(s['baseline_share_pct'], 1)} → {pct(s['current_share_pct'], 1)} ({pp(s['share_change_pp'], 1)}); "
                           f"success rate {pct(s['baseline_rate_pct'])} → {pct(s['current_rate_pct'])} ({pp(s['rate_change_pp'])}).")
    else:
        c.summary = (f"Success rate {direction} by {pp(delta)}. The largest contributor by {d['dimension_label'].lower()} is {top['segment']} "
                     f"({pp(top['contribution_pp'])}, {top['share_of_change_pct']:.0f}% of the change; its success rate moved "
                     f"{pct(top['baseline_rate_pct'])} → {pct(top['current_rate_pct'])} on {pct(top['current_share_pct'], 1)} of eligible volume).")
        c.verdict = {"type": "performance" if mix_frac < 0.3 else "both" if mix_frac < 0.6 else "mix_shift",
                     "label": "Within-segment deterioration" if mix_frac < 0.3 else "Mixed" if mix_frac < 0.6 else "Mix shift", "mix_share_pct": 100 * mix_frac}
        for s in d["segments"][:3]:
            c.facts.append(f"{s['segment']}: contribution {pp(s['contribution_pp'])} (within {pp(s['within_effect_pp'])}, mix {pp(s['mix_effect_pp'])}); "
                           f"volume {num(s['baseline_attempts'])} → {num(s['current_attempts'])}.")
        if (top["share_of_change_pct"] or 0) >= 50 and UNKNOWN not in top["segment"]:
            h, r = recs_mod.for_deterioration(d["dimension_label"], top["segment"], top, _top_failure_shift(c, dim, top))
            c.hypotheses += h; c.recommendations += r
    c.caveats.append("Contribution analysis attributes the aggregate change arithmetically; it identifies where the change occurred, not why.")


def _top_failure_shift(c: Ctx, dim: str, seg: dict) -> dict | None:
    if not seg.get("key") or "failure_code" not in c.user.allowed_dimensions:
        return None
    d_rows = c.run(compile_period_segments(
        c.plan, "failure_code", purpose=f"Failure codes for {seg['segment']}: current vs previous",
        extra_filters=[Filter(dimension=dim, values=[seg["key"]], labels=[seg["segment"]])]))
    codes: dict[str, dict] = {}
    for r in d_rows:
        e = codes.setdefault(r["segment"], {"code": r["segment"], "baseline": 0, "current": 0})
        e["current" if r["period"] == "current" else "baseline"] += r["failed"] or 0
    if not codes:
        return None
    rows = sorted(codes.values(), key=lambda e: -(e["current"] - e["baseline"]))
    c.tables.append({"id": "failure_shift", "title": f"Failure codes for {seg['segment']} — previous vs current", "columns": [
        {"key": "code", "label": "Failure code", "format": "text"}, {"key": "baseline", "label": "Failures (prev)", "format": "count"},
        {"key": "current", "label": "Failures (curr)", "format": "count"}, {"key": "delta", "label": "Change", "format": "count_change"}],
        "rows": [{**e, "delta": e["current"] - e["baseline"]} for e in rows]})
    c.charts.append({"id": "failure_shift_chart", "title": f"Failure codes for {seg['segment']}: previous vs current", "type": "grouped_bar", "x_key": "code",
                     "unit": "count", "series": [{"key": "baseline", "label": "Previous", "unit": "count", "type": "bar"},
                                                 {"key": "current", "label": "Current", "unit": "count", "type": "bar"}], "data": rows})
    top = rows[0]
    c.facts.append(f"Within {seg['segment']}, {top['code']} failures changed {num(top['baseline'])} → {num(top['current'])} — the largest increase of any failure code.")
    return top


def h_mix(c: Ctx) -> None:
    h_contribution(c, mix_focus=True)
    c.caveats.append("Shares and success rates use eligible attempts (SUCCESS + FAILED). Within + mix effects sum exactly to the aggregate change.")


def h_diagnose(c: Ctx) -> None:
    p = c.plan
    b, cur, z = _overall_period(c)
    sr0, sr1 = METRICS["success_rate"].compute(b), METRICS["success_rate"].compute(cur)
    if sr0 is None or sr1 is None:
        c.summary = "Not enough eligible transactions in one of the periods to investigate."
        return
    delta = sr1 - sr0
    c.facts.append(_change_sentence(c, b, cur, z))
    filtered_dims = {f.dimension for f in p.filters if len(f.values) == 1}
    dims = [d for d in DIAGNOSE_DIMENSIONS if d not in filtered_dims]
    allowed = [d for d in dims if d in c.user.allowed_dimensions]
    skipped = [d for d in dims if d not in allowed]
    if skipped:
        c.restricted_notes.append(f"{', '.join(DIMENSIONS[d].label for d in skipped)} drill-downs were omitted: your role ({c.user.role.value}) does not permit them.")
    results = {d: _seg_decomp(c, d) for d in allowed}
    results = {d: r for d, r in results.items() if r.get("valid")}

    daily_range = TimeRange(start=p.comparison_range.start, end=p.time_range.end, label="comparison window")
    daily = [r for r in c.run(compile_daily(p, daily_range, purpose="Daily success rate across both periods")) if r["day"]]
    chart = _daily_chart(daily, "success_rate", "Daily success rate (previous + current period)")
    chart["reference_areas"] = [{"x1": p.time_range.start.isoformat(), "x2": p.time_range.end.isoformat(), "label": "Current period"}]
    c.charts.append(chart)

    material = abs(delta) >= MATERIAL_CHANGE_PP and (z is None or abs(z) >= SIGNIFICANCE_Z)
    summary_rows = []
    for d, r in results.items():
        top = r["segments"][0] if r["segments"] else None
        summary_rows.append({"dimension": r["dimension_label"], "within_effect_pp": r["within_effect_pp"], "mix_effect_pp": r["mix_effect_pp"],
                             "mix_share_pct": (100 * r["mix_effect_pp"] / delta) if abs(delta) > 1e-9 else None,
                             "top_segment": top["segment"] if top else None, "top_contribution_pp": top["contribution_pp"] if top else None,
                             "top_share_of_change_pct": top["share_of_change_pct"] if top else None, "identity_holds": r["identity_holds"]})
    c.tables.append({"id": "dimension_scan", "title": "Decomposition scan across dimensions", "columns": [
        {"key": "dimension", "label": "Dimension", "format": "text"}, {"key": "within_effect_pp", "label": "Within effect", "format": "pp"},
        {"key": "mix_effect_pp", "label": "Mix effect", "format": "pp"}, {"key": "mix_share_pct", "label": "Mix % of change", "format": "percent"},
        {"key": "top_segment", "label": "Largest contributor", "format": "text"}, {"key": "top_contribution_pp", "label": "Its contribution", "format": "pp"},
        {"key": "top_share_of_change_pct", "label": "% of change", "format": "percent"}], "rows": summary_rows})

    if not material:
        direction = "increased" if delta > 0 else "declined"
        c.summary = (f"Payment success rate did not materially decline: it {direction} by {pp(delta)} "
                     f"({pct(sr0)} → {pct(sr1)}){'' if z is None else f', two-proportion z = {z:.1f}'}. No segment-level root cause is warranted.")
        c.verdict = {"type": "no_material_change", "label": "No material change"}
        c.facts.insert(0, c.summary)
        c.recommendations.append(recs_mod.rec("Keep monitoring", "Re-run this analysis on a longer window or a specific segment if a decline is suspected.", "low"))
        _attach_anomalies(c, daily)
        return

    # choose explanation
    mix_best = max(results.values(), key=lambda r: r["mix_effect_pp"] / delta, default=None)
    mix_frac = mix_best["mix_effect_pp"] / delta if mix_best else 0
    def conc(r):
        segs = [s for s in r["segments"] if UNKNOWN not in s["segment"]]
        return max(((s["contribution_pp"] / delta) for s in segs), default=0)
    conc_best = max(results.values(), key=conc, default=None)
    direction = "declined" if delta < 0 else "increased"
    if mix_best and mix_frac >= 0.6:
        d = mix_best
        c.verdict = {"type": "mix_shift", "label": "Transaction mix shift", "dimension": d["dimension"], "mix_share_pct": 100 * mix_frac}
        c.decomposition = d
        c.summary = (f"Payment success rate {direction} by {pp(delta)} ({pct(sr0)} → {pct(sr1)}). The change is explained mainly by a shift in "
                     f"{d['dimension_label'].lower()} mix: mix effect {pp(d['mix_effect_pp'])} ({100 * mix_frac:.0f}% of the change) vs within-segment "
                     f"performance {pp(d['within_effect_pp'])}. Individual {d['dimension_label'].lower()} success rates were broadly stable.")
        movers = sorted(d["segments"], key=lambda s: -abs(s["share_change_pp"]))
        for s in movers[:3]:
            c.facts.append(f"{s['segment']}: share {pct(s['baseline_share_pct'], 1)} → {pct(s['current_share_pct'], 1)}; success rate "
                           f"{pct(s['baseline_rate_pct'])} → {pct(s['current_rate_pct'])} ({pp(s['rate_change_pp'])}).")
        h, r = recs_mod.for_mix(d["dimension_label"], movers, d["mix_effect_pp"], d["within_effect_pp"])
        c.hypotheses += h; c.recommendations += r
        c.charts.append({"id": "share_chart", "title": f"Share of eligible attempts by {d['dimension_label'].lower()}", "type": "grouped_bar", "x_key": "segment",
                         "unit": "percent", "series": [{"key": "baseline_share_pct", "label": "Previous share", "unit": "percent", "type": "bar"},
                                                       {"key": "current_share_pct", "label": "Current share", "unit": "percent", "type": "bar"}], "data": d["segments"]})
    else:
        d = conc_best
        c.decomposition = d
        top = next(s for s in d["segments"] if UNKNOWN not in s["segment"])
        both = mix_best is not None and mix_frac >= 0.3
        c.verdict = {"type": "both" if both else "performance", "label": "Both performance deterioration and mix shift" if both else
                     "Performance deterioration within a segment" if conc(d) >= 0.5 else "Broad-based performance change",
                     "dimension": d["dimension"], "segment": top["segment"], "mix_share_pct": 100 * mix_frac}
        c.summary = (f"Payment success rate {direction} by {pp(delta)} ({pct(sr0)} → {pct(sr1)}). The largest contributor is "
                     f"{d['dimension_label'].lower()} {top['segment']}: {pp(top['contribution_pp'])} ({top['share_of_change_pct']:.0f}% of the change), "
                     f"with its success rate moving {pct(top['baseline_rate_pct'])} → {pct(top['current_rate_pct'])} on "
                     f"{pct(top['current_share_pct'], 1)} of eligible volume. Mix effects are {'material' if both else 'small'} "
                     f"({pp(mix_best['mix_effect_pp']) if mix_best else 'n/a'} by {mix_best['dimension_label'].lower() if mix_best else '-'}).")
        for s in d["segments"][:3]:
            c.facts.append(f"{s['segment']}: success rate {pct(s['baseline_rate_pct'])} → {pct(s['current_rate_pct'])} ({pp(s['rate_change_pp'])}); "
                           f"contribution {pp(s['contribution_pp'])} (within {pp(s['within_effect_pp'])}, mix {pp(s['mix_effect_pp'])}).")
        others = [s for s in d["segments"][1:] if UNKNOWN not in s["segment"] and s["rate_change_pp"] is not None]
        if others:
            avg_other = sum(s["rate_change_pp"] for s in others) / len(others)
            c.facts.append(f"Other {d['dimension_label'].lower()} segments changed by {pp(avg_other)} on average (unweighted), i.e. the decline is "
                           f"{'concentrated' if conc(d) >= 0.5 else 'spread across segments'}.")
        top_code = _top_failure_shift(c, d["dimension"], top)
        h, r = recs_mod.for_deterioration(d["dimension_label"], top["segment"], top, top_code)
        c.hypotheses += h; c.recommendations += r
        if both:
            md = mix_best
            h2, r2 = recs_mod.for_mix(md["dimension_label"], sorted(md["segments"], key=lambda s: -abs(s["share_change_pp"])), md["mix_effect_pp"], md["within_effect_pp"])
            c.hypotheses += h2[:1]; c.recommendations += r2[:1]
    c.tables.append(_decomp_table(c.decomposition, f"Contribution by {c.decomposition['dimension_label'].lower()} (largest contributor dimension)"))
    c.charts.append({"id": "contribution_chart", "title": f"Contribution to success-rate change by {c.decomposition['dimension_label'].lower()} (pp)",
                     "type": "stacked_bar", "x_key": "segment", "unit": "pp",
                     "series": [{"key": "within_effect_pp", "label": "Within-segment (performance)", "unit": "pp", "type": "bar"},
                                {"key": "mix_effect_pp", "label": "Mix (share shift)", "unit": "pp", "type": "bar"}],
                     "data": c.decomposition["segments"][:15]})
    c.facts.append(f"Decomposition identity verified for every dimension: within + mix = direct change (max residual "
                   f"{max(abs(r['residual_pp']) for r in results.values()):.1e} pp).")
    _attach_anomalies(c, daily)
    c.caveats.append("Root-cause output identifies where the change is concentrated (correlation). Confirming the cause requires operational evidence (bank incident reports, logs, release history).")


def _attach_anomalies(c: Ctx, daily: list[dict]) -> None:
    pts = [{"day": r["day"], "v": METRICS["success_rate"].compute(r), "attempts": r["attempts"]} for r in daily]
    if len(pts) < 10:
        return
    scan_start = c.plan.time_range.start.isoformat()
    an = daily_anomalies(pts, "v", scan_start, window=7, min_points=5)
    flagged = [a for a in an if a["flagged"]]
    if flagged:
        c.facts.append("Statistical heuristic (|z| ≥ 3 vs trailing 7-day baseline) flagged: "
                       + ", ".join(f"{a['day']} ({pct(a['value'])}, z = {a['z']:.1f})" for a in flagged[:6]) + ".")


def h_anomaly_daily(c: Ctx) -> None:
    p = c.plan
    metric = "transaction_count" if p.metric == "transaction_count" else "success_rate"
    m = METRICS[metric]
    window = 14
    from ..config import get_settings
    start = max(get_settings().data_start_date, p.time_range.start - timedelta(days=window))
    rng = TimeRange(start=start, end=p.time_range.end, label="scan + baseline")
    daily = [r for r in c.run(compile_daily(p, rng, purpose=f"Daily {m.label.lower()} for anomaly scan (incl. {window}-day baseline)")) if r["day"]]
    pts = [{"day": r["day"], "v": m.compute(r), "attempts": r["attempts"]} for r in daily]
    an = daily_anomalies(pts, "v", p.time_range.start.isoformat(), window=window)
    data = [{"day": a["day"], "value": a["value"], "baseline_mean": a["baseline_mean"],
             "upper": None if a["baseline_mean"] is None else a["baseline_mean"] + 3 * a["baseline_std"],
             "lower": None if a["baseline_mean"] is None else a["baseline_mean"] - 3 * a["baseline_std"], "flagged": a["flagged"]} for a in an]
    c.charts.append({"id": "anomaly_chart", "title": f"Daily {m.label.lower()} vs trailing {window}-day baseline (±3σ band)", "type": "band", "x_key": "day",
                     "unit": m.unit, "series": [{"key": "value", "label": m.label, "unit": m.unit, "type": "line"},
                                                {"key": "baseline_mean", "label": "Baseline mean", "unit": m.unit, "type": "line"},
                                                {"key": "upper", "label": "+3σ", "unit": m.unit, "type": "line"},
                                                {"key": "lower", "label": "−3σ", "unit": m.unit, "type": "line"}], "data": data})
    c.tables.append({"id": "anomaly_table", "title": "Daily anomaly scan", "columns": [
        {"key": "day", "label": "Day", "format": "text"}, {"key": "value", "label": m.label, "format": m.unit},
        {"key": "baseline_mean", "label": "Baseline mean", "format": m.unit}, {"key": "baseline_std", "label": "Baseline σ", "format": "number"},
        {"key": "z", "label": "z-score", "format": "number"}, {"key": "flagged", "label": "Flagged", "format": "bool"}], "rows": an})
    flagged = [a for a in an if a["flagged"]]
    c.summary = (f"{len(flagged)} of {len(an)} day(s) in {_range_txt(p.time_range)} breached the ±3σ band of the trailing {window}-day baseline for "
                 f"{m.label.lower()}{_filters_txt(p)}." + (" Flagged: " + ", ".join(f"{a['day']} ({fmt_metric(a['value'], m.unit)}, z = {a['z']:.1f})" for a in flagged[:6]) + "." if flagged else ""))
    c.facts.append(c.summary)
    c.caveats.append("This is a simple statistical rule (trailing mean ± 3 standard deviations), not a predictive or machine-learning model. Weekly seasonality is not modelled.")
    if flagged:
        c.recommendations.append(recs_mod.rec("Investigate the flagged days", "Run 'Why did payment success rate decline?' and check incident logs for those dates.", "high"))
    c.kpis.append({"metric": "flagged_days", "label": "Flagged days", "unit": "count", "value": len(flagged), "formatted": str(len(flagged)), "primary": True})


def h_segment_outliers(c: Ctx) -> None:
    p = c.plan
    dim = p.dimensions[0]
    rows = c.run(compile_aggregate(p, dimensions=[dim], purpose=f"Failure rate by {DIMENSIONS[dim].label.lower()} for outlier scan", limit=500, order="attempts DESC"))
    total = c.run(compile_aggregate(p, dimensions=[], purpose="Overall failure rate (benchmark)"))[0]
    if not total["eligible"]:
        c.summary = "No eligible transactions in the selected window."
        return
    FR = total["failed"] / total["eligible"]
    out = []
    for r in rows:
        n = r["eligible"] or 0
        if n == 0:
            continue
        fr = r["failed"] / n
        se = (FR * (1 - FR) / n) ** 0.5
        z = (fr - FR) / se if se else 0.0
        out.append({"segment": r[dim], "key": r.get(f"{dim}_key"), "eligible": n, "failed": r["failed"], "failure_rate_pct": 100 * fr,
                    "overall_failure_rate_pct": 100 * FR, "diff_pp": 100 * (fr - FR), "z": z, "flagged": bool(z >= 3 and n >= 50)})
    out.sort(key=lambda x: -x["z"])
    flagged = [o for o in out if o["flagged"]]
    c.use_metric("failure_rate")
    c.tables.append({"id": "outliers", "title": f"Failure-rate outlier scan by {DIMENSIONS[dim].label.lower()}", "columns": [
        {"key": "segment", "label": DIMENSIONS[dim].label, "format": "text"}, {"key": "eligible", "label": "Eligible", "format": "count"},
        {"key": "failed", "label": "Failed", "format": "count"}, {"key": "failure_rate_pct", "label": "Failure rate", "format": "percent"},
        {"key": "diff_pp", "label": "vs overall", "format": "pp"}, {"key": "z", "label": "z-score", "format": "number"},
        {"key": "flagged", "label": "Outlier", "format": "bool"}], "rows": out})
    c.charts.append({"id": "outlier_chart", "title": f"Failure rate by {DIMENSIONS[dim].label.lower()}", "type": "bar", "x_key": "segment", "unit": "percent",
                     "series": [{"key": "failure_rate_pct", "label": "Failure rate", "unit": "percent", "type": "bar"}], "data": out[:25],
                     "reference_lines": [{"y": 100 * FR, "label": f"Overall {pct(100 * FR)}"}], "highlight_key": "flagged"})
    c.kpis.append(_card("failure_rate", total, primary=True, label="Overall failure rate"))
    c.kpis.append({"metric": "outliers", "label": "Outlier segments", "unit": "count", "value": len(flagged), "formatted": str(len(flagged)), "primary": False})
    top_codes: list[dict] = []
    if flagged and flagged[0]["key"] and "failure_code" in c.user.allowed_dimensions:
        fp = p.model_copy(update={"metric": "failed_transactions", "sort": "desc"})
        fc_rows = c.run(compile_aggregate(fp, dimensions=["failure_code"], purpose=f"Failure codes for {flagged[0]['segment']}",
                                          extra_filters=[Filter(dimension=dim, values=[flagged[0]["key"]], labels=[flagged[0]["segment"]])], limit=20))
        tot = sum(r["failed"] for r in fc_rows) or 1
        top_codes = [{"code": r["failure_code"], "failed": r["failed"], "share_pct": 100 * r["failed"] / tot} for r in fc_rows]
        c.tables.append({"id": "outlier_codes", "title": f"Failure codes for {flagged[0]['segment']}", "columns": [
            {"key": "code", "label": "Failure code", "format": "text"}, {"key": "failed", "label": "Failures", "format": "count"},
            {"key": "share_pct", "label": "Share", "format": "percent"}], "rows": top_codes})
    if flagged:
        c.summary = (f"{len(flagged)} {DIMENSIONS[dim].label.lower()}(s) show statistically unusual failure rates for {_range_txt(p.time_range)}: "
                     + "; ".join(f"{o['segment']} {pct(o['failure_rate_pct'])} vs {pct(o['overall_failure_rate_pct'])} overall (z = {o['z']:.1f})" for o in flagged[:3]) + ".")
    else:
        c.summary = f"No {DIMENSIONS[dim].label.lower()} has a failure rate more than 3 standard errors above the overall {pct(100 * FR)} for {_range_txt(p.time_range)}."
    c.facts.append(c.summary)
    h, r = recs_mod.for_outliers(DIMENSIONS[dim].label, flagged, top_codes)
    c.hypotheses += h; c.recommendations += r
    c.caveats.append("Outlier rule (heuristic): binomial z-score of segment failure rate vs overall, flagged when z ≥ 3 with ≥ 50 eligible attempts. Not a predictive model.")


