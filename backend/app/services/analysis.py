# --------------------------------------------------------------------------- context
class Ctx:
    def __init__(self, plan: AnalysisPlan, user: User):
        self.plan, self.user = plan, user
        self.queries: list[QueryRun] = []
        self.kpis: list[dict] = []
        self.charts: list[dict] = []
        self.tables: list[dict] = []
        self.facts: list[str] = []
        self.hypotheses: list[str] = []
        self.recommendations: list[dict] = []
        self.caveats: list[str] = []
        self.restricted_notes: list[str] = []
        self.summary = ""
        self.verdict: dict | None = None
        self.decomposition: dict | None = None
        self.metrics_used: list[str] = [plan.metric]
        self.dimensions_accessed: set[str] = set()

    def run(self, q: CompiledQuery) -> list[dict]:
        self.dimensions_accessed |= q.dimensions
        r = execute(q)
        self.queries.append(r)
        return r.rows

    def use_metric(self, name: str) -> None:
        if name not in self.metrics_used:
            self.metrics_used.append(name)


def _range_txt(tr: TimeRange) -> str:
    return f"{tr.start} to {tr.end} ({tr.days} day{'s' if tr.days != 1 else ''})"


def _filters_txt(plan: AnalysisPlan) -> str:
    if not plan.filters:
        return ""
    return " for " + "; ".join(f"{DIMENSIONS[f.dimension].label.lower()} = {', '.join(f.labels or f.values)}" for f in plan.filters)


def _card(metric: str, row: dict | None, prev_row: dict | None = None, *, primary: bool = False, label: str | None = None) -> dict:
    m = METRICS[metric]
    val = m.compute(row) if row else None
    card = {
        "metric": metric, "label": label or m.label, "unit": m.unit, "value": val, "formatted": fmt_metric(val, m.unit),
        "numerator": row.get(m.numerator) if row else None, "denominator": row.get(m.denominator) if (row and m.denominator) else None,
        "primary": primary, "higher_is_better": m.higher_is_better,
    }
    if prev_row is not None:
        pv = m.compute(prev_row)
        ch = change(val, pv, m.unit)
        card.update({
            "previous": pv, "previous_formatted": fmt_metric(pv, m.unit),
            "change_abs": ch["absolute"], "change_abs_unit": ch["absolute_unit"], "change_pct": ch["relative_pct"],
            "change_formatted": (pp(ch["absolute"]) if m.unit == "percent" else fmt_metric(ch["absolute"], m.unit) if ch["absolute"] is not None else "n/a"),
            "change_pct_formatted": rel(ch["relative_pct"]),
        })
    return card


def _period_rows(rows: list[dict]) -> tuple[dict, dict]:
    empty = {"attempts": 0, "successful": 0, "failed": 0, "pending": 0, "eligible": 0, "tpv_minor": 0, "tpv_txn_count": 0}
    by = {r["period"]: r for r in rows}
    return by.get("baseline", dict(empty)), by.get("current", dict(empty))


def _sr_significance(b: dict, c: dict) -> float | None:
    return two_proportion_z(b["successful"] or 0, b["eligible"] or 0, c["successful"] or 0, c["eligible"] or 0)


