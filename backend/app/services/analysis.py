# --------------------------------------------------------------------------- planner context
_catalog_cache: dict[tuple, list[CatalogEntry]] = {}


def planner_context() -> PlannerContext:
    from ..config import get_settings
    s = get_settings()
    db = get_db()
    key = (str(db.path), db.generation)
    if key not in _catalog_cache:
        cat: list[CatalogEntry] = []
        banks = execute(CompiledQuery("Planner catalogue: banks", "SELECT bank_id, bank_name FROM banks ORDER BY bank_id")).rows
        first_words: dict[str, int] = {}
        for b in banks:
            fw = b["bank_name"].split()[0].lower()
            first_words[fw] = first_words.get(fw, 0) + 1
        for b in banks:
            fw = b["bank_name"].split()[0].lower()
            aliases = [b["bank_id"].lower()] + ([fw, f"{fw} bank"] if first_words[fw] == 1 and len(fw) >= 4 else [])
            cat.append(CatalogEntry("bank", b["bank_id"], b["bank_name"], aliases))
        merchants = execute(CompiledQuery("Planner catalogue: merchants", "SELECT merchant_id, merchant_name, merchant_category, region FROM merchants ORDER BY merchant_id")).rows
        for m in merchants:
            fw = m["merchant_name"].split()[0].lower()
            cat.append(CatalogEntry("merchant", m["merchant_id"], m["merchant_name"], [m["merchant_id"].lower()] + ([fw] if len(fw) >= 6 else [])))
        for category in sorted({m["merchant_category"] for m in merchants}):
            cat.append(CatalogEntry("merchant_category", category, category, [category.lower() + " merchants"]))
        for region in sorted({m["region"] for m in merchants}):
            cat.append(CatalogEntry("region", region, region, [f"{region.lower()}ern", f"{region.lower()} region"]))
        methods = execute(CompiledQuery("Planner catalogue: payment methods", "SELECT payment_method_id, method_name FROM payment_methods")).rows
        method_aliases = {"UPI": ["upi"], "Debit Card": ["debit cards", "debit"], "Credit Card": ["credit cards", "credit"],
                          "Net Banking": ["netbanking", "internet banking", "net banking"]}
        for pm in methods:
            cat.append(CatalogEntry("payment_method", pm["payment_method_id"], pm["method_name"], method_aliases.get(pm["method_name"], [])))
        for code in FAILURE_CODES:
            cat.append(CatalogEntry("failure_code", code, code, [code.lower().replace("_", " ")]))
        _catalog_cache.clear()
        _catalog_cache[key] = cat
    return PlannerContext(data_start=s.data_start_date, data_end=s.data_end_date, catalog=_catalog_cache[key])


# --------------------------------------------------------------------------- entry point
def enforce_rbac(plan: AnalysisPlan, user: User) -> None:
    requested = set(plan.dimensions) | {f.dimension for f in plan.filters}
    denied = sorted(requested - user.allowed_dimensions)
    if denied:
        labels = ", ".join(DIMENSIONS[d].label.lower() for d in denied)
        raise AuthorizationError(
            f"Access denied: your role ({user.role.value}) is not permitted to run {labels}-level analysis. "
            "Bank and merchant drill-downs require the ANALYST or ADMIN role.",
            code="ROLE_RESTRICTED_DIMENSION",
            details={"role": user.role.value, "restricted_dimensions": denied, "allowed_dimensions": sorted(user.allowed_dimensions)},
        )


def authorize_stored_result(result: dict[str, Any], user: User) -> None:
    """Re-check a stored analysis against the reader's *current* role (hardening iteration 6).

    Results are saved with the dimensions their queries touched. Without this check an analyst who was
    later demoted to VIEWER could still open earlier bank/merchant breakdowns from history."""
    if result.get("status") != "completed":
        return
    access = result.get("access")
    if access is None:  # stored before access metadata existed: only roles with every dimension may read it
        needed = set(DIMENSIONS) - {"day"}
    else:
        needed = set(access.get("dimensions", []))
    denied = sorted(needed - user.allowed_dimensions)
    if denied:
        raise AuthorizationError(
            f"This saved analysis contains {', '.join(DIMENSIONS[d].label.lower() for d in denied if d in DIMENSIONS)}-level data "
            f"that your current role ({user.role.value}) cannot view. Ask the question again to get a permitted view.",
            code="ROLE_RESTRICTED_DIMENSION", details={"restricted_dimensions": denied, "role": user.role.value})


def run_analysis(question: str, user: User, scenario_id: str | None = None) -> dict[str, Any]:
    t0 = time.perf_counter()
    db = get_db()
    ctx = planner_context()
    outcome = plan_question(question, ctx)
    result: dict[str, Any] = {
        "id": uuid.uuid4().hex,
        "question": question,
        "created_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "planner": {"engine": ENGINE_NAME, "version": ENGINE_VERSION, "external_ai": False},
        "status": outcome.status,
        "scenario_id": scenario_id,
        "data_profile": db.profile,
        "data_window": {"start": ctx.data_start.isoformat(), "end": ctx.data_end.isoformat()},
    }
    if outcome.status != "planned":
        result.update({"message": outcome.message, "suggestions": outcome.suggestions,
                       "interpretation": {"matched_terms": [t.model_dump() for t in outcome.matched_terms]}})
        return result
    plan = outcome.plan
    assert plan is not None
    enforce_rbac(plan, user)

    c = Ctx(plan, user)
    HANDLERS[plan.intent](c)

    quality = quality_summary_for_analysis()
    c.recommendations += recs_mod.for_quality(quality["warnings"])
    tables_used = sorted({t for q in c.queries for t in q.tables})
    result.update({
        "status": "completed",
        "summary": c.summary,
        "verdict": c.verdict,
        "interpretation": {
            "intent": plan.intent, "intent_label": INTENT_LABELS[plan.intent],
            "metric": plan.metric, "metric_label": METRICS[plan.metric].label,
            "dimensions": [{"name": d, "label": DIMENSIONS[d].label} for d in plan.dimensions],
            "filters": [f.model_dump() for f in plan.filters],
            "time_range": plan.time_range.as_dict(),
            "comparison_range": plan.comparison_range.as_dict() if plan.comparison_range else None,
            "assumptions": plan.assumptions,
            "matched_terms": [t.model_dump() for t in plan.matched_terms],
            "confidence": plan.confidence,
        },
        "plan": plan.summary_dict(),
        "kpis": c.kpis,
        "charts": c.charts,
        "tables": c.tables,
        "facts": c.facts,
        "hypotheses": c.hypotheses,
        "recommendations": c.recommendations,
        "caveats": c.caveats,
        "restricted_notes": c.restricted_notes,
        "access": {"dimensions": sorted(c.dimensions_accessed)},
        "decomposition": _decomp_meta(c.decomposition),
        "metric_definitions": [METRICS[mn].as_dict() for mn in c.metrics_used],
        "datasets": [{"table": t, "description": TABLE_DESCRIPTIONS.get(t, "")} for t in tables_used],
        "queries": [{**q.meta(), "preview": q.rows[:25], "columns": q.columns} for q in c.queries],
        "data_quality": quality,
        "execution": {
            "total_ms": round((time.perf_counter() - t0) * 1000, 1),
            "query_count": len(c.queries),
            "cache_hits": sum(1 for q in c.queries if q.cached),
            "sql_ms": round(sum(q.duration_ms for q in c.queries), 1),
            "rows_returned": sum(q.row_count for q in c.queries),
            "db_generation": db.generation,
        },
    })
    return result


def _decomp_meta(d: dict | None) -> dict | None:
    if not d:
        return None
    keys = ("dimension", "dimension_label", "baseline_rate_pct", "current_rate_pct", "direct_change_pp", "within_effect_pp",
            "mix_effect_pp", "residual_pp", "identity_holds")
    return {k: d.get(k) for k in keys if k in d}
